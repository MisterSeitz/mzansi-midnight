  const data = JSON.parse(fs.readFileSync(filePath, 'utf-8'));

  let addedCount = 0;
  for (const [key, translations] of Object.entries(newKeys)) {
    data[key] = translations[lang] || translations.en;
    addedCount++;
  }

  // Sort keys
  const sorted = {};
  for (const k of Object.keys(data).sort()) {
    sorted[k] = data[k];
  }

