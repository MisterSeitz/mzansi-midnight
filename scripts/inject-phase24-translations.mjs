for (const lang of LANGS) {
  const filePath = path.join(DICT_DIR, `${lang}.json`);
  if (!fs.existsSync(filePath)) {
    console.error(`Missing language file: ${filePath}`);
    continue;
  }
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let addedCount = 0;

  for (const [key, translations] of Object.entries(PHASE_24_TRANSLATIONS)) {
    if (translations[lang]) {
      content[key] = translations[lang];
      addedCount++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf8');
  console.log(`Updated ${lang}.json with ${addedCount} Phase 24 translations.`);
}

