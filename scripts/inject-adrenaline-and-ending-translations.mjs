const i18nDir = path.join(process.cwd(), 'data', 'i18n');
const languages = ['en', 'af', 'zu', 'xh', 'st', 'nso', 'tn', 'ts', 'ss', 've'];

languages.forEach((lang) => {
  const filePath = path.join(i18nDir, `${lang}.json`);
  const dict = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const additions = TRANSLATIONS[lang] || TRANSLATIONS.en;

  let added = 0;
  for (const [key, val] of Object.entries(additions)) {
    if (!dict[key]) {
      dict[key] = val;
      added++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(dict, null, 2) + '\n');
  console.log(`[${lang}] Injected ${added} keys. Total keys: ${Object.keys(dict).length}`);
});

console.log('All 10 language dictionaries updated with 100% key parity!');
